export type IconName = keyof typeof GRIDS;

const cache = new Map<IconName, string>();

/** Inline SVG for a pixel icon, sized by CSS (defaults to 1em). */
export function icon(name: IconName, cls = 'icon-px'): string {
  let body = cache.get(name);
  if (!body) {
    const rows = GRIDS[name];
    let rects = '';
    rows.forEach((row, y) => {
      // Merge horizontal runs of the same kind into one rect.
      for (let x = 0; x < row.length;) {
        const ch = row[x];
        if (ch === '.') { x++; continue; }
        let w = 1;
        while (x + w < row.length && row[x + w] === ch) w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1"${ch === '+' ? ' fill-opacity="0.45"' : ''}/>`;
        x += w;
      }
    });
    body = rects;
    cache.set(name, body);
  }
  return `<svg class="${cls}" viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}
